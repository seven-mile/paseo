import { randomBytes, timingSafeEqual } from "node:crypto";
import { chmodSync, mkdirSync, writeFileSync } from "node:fs";
import { createServer, type IncomingMessage, type Server } from "node:http";
import type { AddressInfo } from "node:net";
import { delimiter, join } from "node:path";
import { z } from "zod";
import type { ApprovalAction } from "../shared/models";

// Remote effects reach the forge through these CLIs. Each one gets a POSIX shim that runs the
// real binary directly unless the arguments name a gated subcommand; only then does it start
// Node to ask the gate. Calling a binary by absolute path skips the shim: the gate keeps a
// cooperative agent honest, and is not a sandbox.
export const gatedTools = ["git", "gh", "glab"] as const;
export type GatedTool = (typeof gatedTools)[number];

// git global options whose value is the next argument.
const gitValueOptions = new Set([
  "-C",
  "-c",
  "--git-dir",
  "--work-tree",
  "--namespace",
  "--config-env",
]);

function positionals(args: readonly string[], valueOptions: ReadonlySet<string>): string[] {
  const result: string[] = [];
  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    if (valueOptions.has(arg)) index += 1;
    else if (!arg.startsWith("-")) result.push(arg);
  }
  return result;
}

export function classifyCommand(tool: string, args: readonly string[]): ApprovalAction | null {
  if (tool === "git") {
    // Only the subcommand position counts: options after it belong to the subcommand.
    for (let index = 0; index < args.length; index += 1) {
      const arg = args[index];
      if (gitValueOptions.has(arg)) index += 1;
      else if (!arg.startsWith("-")) return arg === "push" ? "push" : null;
    }
    return null;
  }
  if (tool === "gh") {
    const [group, verb] = positionals(args, new Set(["-R", "--repo"]));
    if (group !== "pr") return null;
    if (verb === "create") return "pr_create";
    if (verb === "ready") return "pr_ready";
    if (verb === "merge") return "pr_merge";
    return null;
  }
  if (tool === "glab") {
    const [group, verb] = positionals(args, new Set(["-R", "--repo"]));
    if (group !== "mr") return null;
    if (verb === "create") return "mr_create";
    if (verb === "merge") return "mr_merge";
    return null;
  }
  return null;
}

function shellQuote(value: string): string {
  return `'${value.replaceAll("'", `'\\''`)}'`;
}

// The shell pre-filter mirrors classifyCommand loosely and errs toward asking: the gate
// classifies again and allows anything it does not recognize.
function prefilter(tool: GatedTool): string {
  if (tool === "git") {
    return `skip=
for arg in "$@"; do
  if [ -n "$skip" ]; then skip=; continue; fi
  case $arg in
    -C|-c|--git-dir|--work-tree|--namespace|--config-env) skip=1 ;;
    -*) ;;
    push) gated=1; break ;;
    *) break ;;
  esac
done`;
  }
  const [group, verbs] = tool === "gh" ? ["pr", "create|ready|merge"] : ["mr", "create|merge"];
  return `skip=
seen=
for arg in "$@"; do
  if [ -n "$skip" ]; then skip=; continue; fi
  case $arg in
    -R|--repo) skip=1; continue ;;
    -*) continue ;;
  esac
  if [ -z "$seen" ]; then
    [ "$arg" = ${group} ] || break
    seen=1
    continue
  fi
  case $arg in ${verbs}) gated=1 ;; esac
  break
done`;
}

export function shimScript(input: {
  tool: GatedTool;
  binDirectory: string;
  helperPath: string;
  nodePath: string;
}): string {
  return `#!/bin/sh
# Generated by Paseo Swarm on daemon start. Holds remote effects for human approval.
gate_bin=${shellQuote(input.binDirectory)}
rest=
old_ifs=$IFS
IFS=:
set -f
for entry in $PATH; do
  [ "$entry" = "$gate_bin" ] && continue
  rest=\${rest:+$rest:}$entry
done
set +f
IFS=$old_ifs
real=$(PATH=$rest command -v ${input.tool}) || {
  echo "paseo-swarm: ${input.tool} is not installed" >&2
  exit 127
}
gated=
${prefilter(input.tool)}
if [ -n "$gated" ]; then
  ELECTRON_RUN_AS_NODE=1 ${shellQuote(input.nodePath)} ${shellQuote(input.helperPath)} ${input.tool} "$@" || exit $?
fi
exec "$real" "$@"
`;
}

// Prints each line the gate streams: a hold notice as soon as the request is recorded, then the
// decision. Exit 0 lets the shim run the real command; 75 (EX_TEMPFAIL) means still pending.
export function helperScript(input: { url: string; token: string }): string {
  return `// Generated by Paseo Swarm on daemon start.
const [tool, ...args] = process.argv.slice(2);
const fail = (message, code) => {
  process.stderr.write("paseo-swarm: " + message + "\\n");
  process.exit(code);
};
let response;
try {
  response = await fetch(${JSON.stringify(input.url)}, {
    method: "POST",
    headers: { authorization: ${JSON.stringify(`Bearer ${input.token}`)}, "content-type": "application/json" },
    body: JSON.stringify({ agentId: process.env.PASEO_AGENT_ID ?? "", tool, args, cwd: process.cwd() }),
  });
} catch (error) {
  fail("the approval gate is unreachable, so " + tool + " was not run: " + error.message, 1);
}
if (!response.ok || !response.body) fail("the approval gate refused the request (" + response.status + ")", 1);
let buffered = "";
const decoder = new TextDecoder();
for await (const chunk of response.body) {
  buffered += decoder.decode(chunk, { stream: true });
  let newline;
  while ((newline = buffered.indexOf("\\n")) >= 0) {
    const event = JSON.parse(buffered.slice(0, newline));
    buffered = buffered.slice(newline + 1);
    if (event.type === "held") {
      process.stderr.write("paseo-swarm: " + event.message + "\\n");
      continue;
    }
    if (event.decision === "allow") process.exit(0);
    fail(event.message, event.decision === "pending" ? 75 : 1);
  }
}
fail("the approval gate closed without a decision, so " + tool + " was not run", 1);
`;
}

export const gateRequestSchema = z.object({
  agentId: z.string(),
  tool: z.enum(gatedTools),
  args: z.array(z.string()),
  cwd: z.string(),
});
export type GateRequest = z.infer<typeof gateRequestSchema>;

export type GateEvent =
  | { type: "held"; approvalId: string; message: string }
  | { type: "decision"; decision: "allow" | "deny" | "pending"; message: string };

export type GateHandler = (
  request: GateRequest,
  emit: (event: GateEvent) => void,
  signal: AbortSignal,
) => Promise<void>;

export interface RunningGate {
  binDirectory: string;
  // Prepends the shim directory once, so nested agents do not stack copies.
  env(base: Record<string, string>): Record<string, string>;
  close(): Promise<void>;
}

async function readBody(request: IncomingMessage): Promise<unknown> {
  const chunks: Buffer[] = [];
  let size = 0;
  for await (const chunk of request) {
    size += (chunk as Buffer).length;
    if (size > 1_000_000) throw new Error("Request body is too large");
    chunks.push(chunk as Buffer);
  }
  return JSON.parse(Buffer.concat(chunks).toString("utf8"));
}

function authorized(header: string | undefined, token: string): boolean {
  const expected = Buffer.from(`Bearer ${token}`);
  const actual = Buffer.from(header ?? "");
  return actual.length === expected.length && timingSafeEqual(actual, expected);
}

export async function startGate(input: {
  directory: string;
  handler: GateHandler;
  nodePath?: string;
}): Promise<RunningGate> {
  const token = randomBytes(32).toString("hex");
  const server: Server = createServer((request, response) => {
    if (request.method !== "POST" || !authorized(request.headers.authorization, token)) {
      response.writeHead(403).end();
      return;
    }
    const abort = new AbortController();
    response.on("close", () => abort.abort());
    void (async () => {
      let parsed: GateRequest;
      try {
        parsed = gateRequestSchema.parse(await readBody(request));
      } catch {
        response.writeHead(400).end();
        return;
      }
      response.writeHead(200, { "content-type": "application/x-ndjson" });
      const emit = (event: GateEvent) => {
        if (!response.writableEnded) response.write(`${JSON.stringify(event)}\n`);
      };
      try {
        await input.handler(parsed, emit, abort.signal);
      } catch (error) {
        emit({
          type: "decision",
          decision: "deny",
          message: `the approval gate failed, so the command was not run: ${error instanceof Error ? error.message : String(error)}`,
        });
      }
      response.end();
    })();
  });
  // The hold is longer than Node's default request timeouts.
  server.requestTimeout = 0;
  server.headersTimeout = 0;
  await new Promise<void>((resolve, reject) => {
    server.once("error", reject);
    server.listen(0, "127.0.0.1", () => resolve());
  });
  // The gate alone never keeps the plugin process alive.
  server.unref();
  const { port } = server.address() as AddressInfo;

  const binDirectory = join(input.directory, "bin");
  mkdirSync(binDirectory, { recursive: true, mode: 0o700 });
  chmodSync(input.directory, 0o700);
  const helperPath = join(input.directory, "gate.mjs");
  writeFileSync(helperPath, helperScript({ url: `http://127.0.0.1:${port}/gate`, token }), {
    mode: 0o600,
  });
  for (const tool of gatedTools) {
    const shimPath = join(binDirectory, tool);
    writeFileSync(
      shimPath,
      shimScript({ tool, binDirectory, helperPath, nodePath: input.nodePath ?? process.execPath }),
    );
    chmodSync(shimPath, 0o700);
  }

  return {
    binDirectory,
    env(base) {
      const current = base.PATH ?? process.env.PATH ?? "";
      const rest = current.split(delimiter).filter((entry) => entry && entry !== binDirectory);
      return { ...base, PATH: [binDirectory, ...rest].join(delimiter) };
    },
    close: () =>
      new Promise<void>((resolve) => {
        server.closeAllConnections();
        server.close(() => resolve());
      }),
  };
}
